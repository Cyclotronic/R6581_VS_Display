"""Builds Core/Inc/boot_logo.h: Ian Johnston's cartoon character as a 1-bit bitmap for the boot screen.
Source: the front silkscreen layer of his own PCB release, Hardware/7680-Controller_backside4_V1_2.zip (the figure is drawn there as
filled Gerber regions). The same figure appears in the banner of ianjohnston.com. Only the figure is used, not the banner text.
usage: python -I make_logo.py <repo-root> [height_px]   (default height 96; width follows the aspect ratio)
Bitmap layout: row-major in SCREEN orientation (row 0 = top), MSB = left pixel, each row padded to whole bytes."""
import re, sys, os, zipfile
from PIL import Image, ImageDraw
repo = sys.argv[1]; H = int(sys.argv[2]) if len(sys.argv) > 2 else 96
z = zipfile.ZipFile(os.path.join(repo, "Hardware", "7680-Controller_backside4_V1_2.zip"))
t = z.read("7680-Controller_backside4-F_Silkscreen.gbr").decode("latin1")
dec = int(re.search(r"%FSLAX\d(\d)Y\d(\d)\*%", t).group(1)); sc = 10 ** dec
regions = []; cur = None; pol = "D"; x = y = 0.0; inreg = False
for m in re.finditer(r"%LP([DC])\*%|(G36\*)|(G37\*)|X(-?\d+)Y(-?\d+)D0([123])\*|X(-?\d+)D0([123])\*|Y(-?\d+)D0([123])\*", t):
    if m.group(1): pol = m.group(1)
    elif m.group(2): inreg = True; cur = []
    elif m.group(3):
        inreg = False
        if cur: regions.append((pol, cur))
        cur = None
    elif m.group(4):
        x = int(m.group(4)) / sc; y = int(m.group(5)) / sc
        if inreg:
            if m.group(6) == "2" and cur: regions.append((pol, cur)); cur = []
            cur.append((x, y))
    elif m.group(7):
        x = int(m.group(7)) / sc
        if inreg: cur.append((x, y))
    elif m.group(9):
        y = int(m.group(9)) / sc
        if inreg: cur.append((x, y))
pts = [p for _, r in regions for p in r]
x0, x1 = min(p[0] for p in pts), max(p[0] for p in pts); y0, y1 = min(p[1] for p in pts), max(p[1] for p in pts)
SS = 8; W = round(H * (x1 - x0) / (y1 - y0)); ppmm = H * SS / (y1 - y0)
big = Image.new("L", (W * SS + 2, H * SS + 2), 0); d = ImageDraw.Draw(big)
for p, r in regions:
    if len(r) > 2: d.polygon([((a - x0) * ppmm, (y1 - b) * ppmm) for a, b in r], fill=255 if p == "D" else 0)
small = big.resize((W, H), Image.LANCZOS).point(lambda v: 255 if v >= 45 else 0)
bpr = (W + 7) // 8; data = bytearray()
for r in range(H):
    for c in range(bpr):
        b = 0
        for k in range(8):
            cc = c * 8 + k
            b = (b << 1) | (1 if cc < W and small.getpixel((cc, r)) else 0)
        data.append(b)
with open(os.path.join(repo, "Core", "Inc", "boot_logo.h"), "w", newline="\n") as f:
    f.write("// Generated by docs/tools/make_logo.py - do not edit. Ian Johnston's cartoon character (from his PCB silkscreen artwork).\n")
    f.write(f"#define BOOT_LOGO_W {W}   // pixels, as seen on screen\n#define BOOT_LOGO_H {H}\n#define BOOT_LOGO_BPR {bpr}   // bytes per row, MSB = left pixel\n")
    f.write("static const uint8_t boot_logo[BOOT_LOGO_H * BOOT_LOGO_BPR] = {\n")
    for i in range(0, len(data), 16): f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")
small.resize((W * 4, H * 4), Image.NEAREST).save(os.path.join(os.environ.get("TEMP", "."), "boot_logo_preview.png"))
print("boot_logo.h:", W, "x", H, len(data), "bytes")
