static uint8_t InverseByte(uint8_t a) {
	a = ((a & 0x55) << 1) | ((a & 0xAA) >> 1);
	a = ((a & 0x33) << 2) | ((a & 0xCC) >> 2);
	return (a >> 4) | (a << 4);
}


